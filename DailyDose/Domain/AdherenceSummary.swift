import Foundation

/// A shareable, human-readable account of a period's adherence.
///
/// History had no toolbar at all, and export is the action it was missing — the
/// screen shows the data, so it should be able to hand it over. This is what
/// the share button produces today: plain text that reads correctly in Messages,
/// Mail or Notes without any rendering, which is exactly what someone needs when
/// a doctor asks "how have you been getting on with it?".
///
/// It is deliberately not a medical record, and it says so at the bottom. When
/// the PDF report exists it becomes another rendering of this same data; the
/// share button doesn't move.
enum AdherenceSummary {

    struct Line: Equatable, Sendable {
        let name: String
        let summary: AdherenceCalculator.Summary
    }

    /// Builds the summary text.
    ///
    /// Pure: hand it records and names, get a string. No formatting decisions
    /// are made anywhere else, and every number here comes from the same
    /// `AdherenceCalculator` the History screen renders — so the text a user
    /// shares can never disagree with the screen they shared it from.
    static func text(
        overall: AdherenceCalculator.Summary,
        byMedication: [Line],
        days: Int,
        now: Date,
        calendar: Calendar = .current,
        locale: Locale = .current
    ) -> String {
        var out: [String] = []

        out.append(String(localized: "Daily Dose — Adherence Summary"))
        out.append(dateRange(days: days, now: now, calendar: calendar, locale: locale))
        out.append("")

        if let percent = overall.percent {
            out.append(String(localized: "Overall: \(percent)% taken"))
            out.append(String(localized: "\(overall.taken) taken · \(overall.skipped) skipped · \(overall.missed) missed"))
        } else {
            out.append(String(localized: "No doses recorded in this period."))
        }

        if !byMedication.isEmpty {
            out.append("")
            out.append(String(localized: "By medication"))
            // Pad the names so the percentages line up in a monospaced mail
            // client without needing a table. Degrades to a plain list in a
            // proportional font rather than looking broken.
            let width = min(byMedication.map(\.name.count).max() ?? 0, 24)
            for line in byMedication {
                let name = line.name.count > width
                    ? String(line.name.prefix(width - 1)) + "…"
                    : line.name.padding(toLength: width, withPad: " ", startingAt: 0)
                let percent = line.summary.percent.map { "\($0)%" } ?? "—"
                out.append("  \(name)  \(percent.leftPadded(to: 4))   \(line.summary.taken)/\(line.summary.total)")
            }
        }

        out.append("")
        out.append(String(localized: "Generated by Daily Dose. This is a personal record, not a medical document."))

        return out.joined(separator: "\n")
    }

    private static func dateRange(days: Int, now: Date, calendar: Calendar, locale: Locale) -> String {
        let today = calendar.startOfDay(for: now)
        let start = calendar.date(byAdding: .day, value: -(days - 1), to: today) ?? today
        let from = start.formatted(.dateTime.day().month(.abbreviated).year().locale(locale))
        let to = now.formatted(.dateTime.day().month(.abbreviated).year().locale(locale))
        return String(localized: "\(from) – \(to) · \(days) days")
    }

    /// A filename that sorts chronologically and is identical on every device —
    /// fixed locale, ISO ordering, no spaces.
    static func fileName(days: Int, now: Date) -> String {
        let stamp = now.formatted(.iso8601.year().month().day().dateSeparator(.dash))
        return "daily-dose-adherence-\(days)d-\(stamp).txt"
    }
}

private extension String {
    /// Right-aligns short strings in a fixed column.
    func leftPadded(to width: Int) -> String {
        count >= width ? self : String(repeating: " ", count: width - count) + self
    }
}
